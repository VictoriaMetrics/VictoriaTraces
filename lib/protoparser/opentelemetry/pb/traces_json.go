package pb

import (
	"encoding/json"
	"fmt"
	"strconv"
	"strings"
)

// parseUnixTimestampByte parses fixed64 timestamp from OTLP/JSON, which may be either a JSON number or a decimal string.
// Absent and null timestamps are treated as the default value 0.
//
// See https://protobuf.dev/programming-guides/json/
func parseUnixTimestampByte(b []byte) (uintVal uint64, err error) {
	if len(b) == 0 || string(b) == "null" {
		return 0, nil
	}
	firstByte := b[0]
	if firstByte >= '0' && firstByte <= '9' {
		// positive number
		err = json.Unmarshal(b, &uintVal)
		if err != nil {
			return 0, err
		}
		return uintVal, nil
	}

	// string
	unquoted, err := strconv.Unquote(string(b))
	if err != nil {
		return 0, err
	}
	uintVal, err = strconv.ParseUint(unquoted, 10, 64)
	if err != nil {
		return 0, err
	}
	return uintVal, nil
}

// marshalUnixTimestamp encodes fixed64 timestamp as a decimal string for OTLP/JSON.
//
// See https://protobuf.dev/programming-guides/json/
func marshalUnixTimestamp(v uint64) json.RawMessage {
	return json.RawMessage(strconv.Quote(strconv.FormatUint(v, 10)))
}

// spanAlias has no methods, so json.Unmarshal and json.Marshal don't recurse into Span.UnmarshalJSON and Span.MarshalJSON.
type spanAlias Span

// spanJSON is used by Span.UnmarshalJSON and Span.MarshalJSON for handling startTimeUnixNano and endTimeUnixNano,
// which may be either JSON numbers or decimal strings in OTLP/JSON, and are encoded as decimal strings
// according to the protobuf JSON mapping for fixed64.
type spanJSON struct {
	*spanAlias

	StartTimeUnixNanoRaw json.RawMessage `json:"startTimeUnixNano"`
	EndTimeUnixNanoRaw   json.RawMessage `json:"endTimeUnixNano"`
}

// UnmarshalJSON implements json.Unmarshaler.
//
// startTimeUnixNano and endTimeUnixNano may be either JSON numbers or decimal strings.
// traceId, spanId and parentSpanId are case-insensitive hex-encoded strings, so they are converted to lowercase.
// https://opentelemetry.io/docs/specs/otlp/#json-protobuf-encoding
func (s *Span) UnmarshalJSON(data []byte) (err error) {
	spJSON := spanJSON{spanAlias: (*spanAlias)(s)}
	if err = json.Unmarshal(data, &spJSON); err != nil {
		return err
	}

	if s.StartTimeUnixNano, err = parseUnixTimestampByte(spJSON.StartTimeUnixNanoRaw); err != nil {
		return fmt.Errorf("cannot parse startTimeUnixNano: %w", err)
	}
	if s.EndTimeUnixNano, err = parseUnixTimestampByte(spJSON.EndTimeUnixNanoRaw); err != nil {
		return fmt.Errorf("cannot parse endTimeUnixNano: %w", err)
	}

	// hex-encoded strings generated by standard-library are lowercase. https://github.com/golang/go/blob/master/src/encoding/hex/hex.go#L17
	s.TraceID = strings.ToLower(s.TraceID)
	s.SpanID = strings.ToLower(s.SpanID)
	s.ParentSpanID = strings.ToLower(s.ParentSpanID)
	return nil
}

// MarshalJSON implements json.Marshaler.
//
// startTimeUnixNano and endTimeUnixNano are encoded as decimal strings according to the protobuf JSON mapping for fixed64.
// https://protobuf.dev/programming-guides/json/
func (s *Span) MarshalJSON() ([]byte, error) {
	spJSON := spanJSON{
		spanAlias:            (*spanAlias)(s),
		StartTimeUnixNanoRaw: marshalUnixTimestamp(s.StartTimeUnixNano),
		EndTimeUnixNanoRaw:   marshalUnixTimestamp(s.EndTimeUnixNano),
	}
	return json.Marshal(&spJSON)
}

// spanEventAlias has no methods, so json.Unmarshal and json.Marshal don't recurse into SpanEvent.UnmarshalJSON and SpanEvent.MarshalJSON.
type spanEventAlias SpanEvent

// spanEventJSON is used by SpanEvent.UnmarshalJSON and SpanEvent.MarshalJSON for handling timeUnixNano,
